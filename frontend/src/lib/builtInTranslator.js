/**
 * Translates English text to Arabic using built-in dictionary, grammar rules & transliteration
 * @param {string} text - English input string
 * @returns {string} - Arabic translation
 */
export function translateEnglishToArabic(text) {
  if (!text || typeof text !== 'string') return '';
  const trimmed = text.trim();
  if (!trimmed) return '';
  
  // If already Arabic, return as-is
  if (isArabicText(trimmed)) return trimmed;

  const normalized = normalizeText(trimmed);

  // 1. Direct dictionary match
  if (DICTIONARY[normalized]) {
    return cleanTranslation(DICTIONARY[normalized]);
  }

  // 1b. Known proper name match (people's names) — takes priority over the
  // generic phonetic engine, which cannot reliably guess correct Arabic
  // spelling for names (e.g. double letters, silent sounds).
  if (EN_NAMES[normalized]) {
    return EN_NAMES[normalized];
  }

  // 2. Extract unit/measurement suffix or prefix if present e.g. "Almarai Milk 1L" -> "حليب المراعي 1 لتر"
  let extractedUnitAr = '';
  let cleanedBaseText = trimmed;
  for (const unit of UNIT_PATTERNS) {
    const match = cleanedBaseText.match(unit.regex);
    if (match) {
      extractedUnitAr = unit.ar(match[1]);
      cleanedBaseText = cleanedBaseText.replace(match[0], '').trim();
      break;
    }
  }

  const baseNorm = normalizeText(cleanedBaseText);
  if (baseNorm && DICTIONARY[baseNorm]) {
    const baseAr = cleanTranslation(DICTIONARY[baseNorm]);
    return extractedUnitAr ? `${baseAr} ${extractedUnitAr}` : baseAr;
  }

  // 3. Tokenize words and compound phrases
  const words = cleanedBaseText.split(/\s+/).filter(Boolean);
  if (words.length === 0) return extractedUnitAr || trimmed;

  // Try sub-phrase chunks (n-grams from longest to 1)
  const translatedTokens = [];
  let i = 0;
  while (i < words.length) {
    let matched = false;
    // Check 3-word phrase
    if (i + 2 < words.length) {
      const phrase3 = `${words[i]} ${words[i+1]} ${words[i+2]}`.toLowerCase();
      if (DICTIONARY[phrase3]) {
        translatedTokens.push(cleanTranslation(DICTIONARY[phrase3]));
        i += 3;
        matched = true;
        continue;
      }
    }
    // Check 2-word phrase
    if (i + 1 < words.length) {
      const phrase2 = `${words[i]} ${words[i+1]}`.toLowerCase();
      if (DICTIONARY[phrase2]) {
        translatedTokens.push(cleanTranslation(DICTIONARY[phrase2]));
        i += 2;
        matched = true;
        continue;
      }
    }
    // Single word
    const singleWord = words[i].toLowerCase();
    // Numbers or symbols stay as is
    if (/^[\d+/*\-#.]+$/.test(singleWord)) {
      translatedTokens.push(words[i]);
    } else if (DICTIONARY[singleWord]) {
      translatedTokens.push(cleanTranslation(DICTIONARY[singleWord]));
    } else if (EN_NAMES[singleWord]) {
      translatedTokens.push(EN_NAMES[singleWord]);
    } else {
      // Phonetic transliteration for unknown proper names / brand words
      translatedTokens.push(transliterateEnToAr(words[i]));
    }
    i++;
  }

  let finalArabic = translatedTokens.join(' ').trim();
  if (extractedUnitAr) {
    finalArabic = `${finalArabic} ${extractedUnitAr}`;
  }

  return finalArabic || trimmed;
}

/**
 * Translates Arabic text to English using built-in dictionary & rules
 * @param {string} text - Arabic input string
 * @returns {string} - English translation
 */
export function translateArabicToEnglish(text) {
  if (!text || typeof text !== 'string') return '';
  const trimmed = text.trim();
  if (!trimmed) return '';
  
  // If already pure Latin/English, return as-is
  if (!isArabicText(trimmed)) return trimmed;

  const normalized = normalizeText(trimmed);

  // 1. Direct reverse dictionary match
  if (REVERSE_DICTIONARY[normalized]) {
    return capitalizeWords(REVERSE_DICTIONARY[normalized]);
  }
  if (AR_NAMES[normalized]) {
    return AR_NAMES[normalized];
  }

  // 2. Extract unit/measurement suffix if present e.g. "حليب المراعي 1 لتر"
  let extractedUnitEn = '';
  let cleanedBaseText = trimmed;
  for (const unit of UNIT_PATTERNS) {
    const match = cleanedBaseText.match(unit.regex);
    if (match) {
      extractedUnitEn = unit.en(match[1]);
      cleanedBaseText = cleanedBaseText.replace(match[0], '').trim();
      break;
    }
  }

  // Check Arabic name / dictionary on cleaned base
  const cleanNorm = normalizeText(cleanedBaseText);
  if (cleanNorm && REVERSE_DICTIONARY[cleanNorm]) {
    const baseEn = capitalizeWords(REVERSE_DICTIONARY[cleanNorm]);
    return extractedUnitEn ? `${baseEn} ${extractedUnitEn}` : baseEn;
  }
  if (cleanNorm && AR_NAMES[cleanNorm]) {
    const nameEn = AR_NAMES[cleanNorm];
    return extractedUnitEn ? `${nameEn} ${extractedUnitEn}` : nameEn;
  }

  // 3. Tokenize words
  const words = cleanedBaseText.split(/\s+/).filter(Boolean);
  const translatedTokens = [];

  for (const w of words) {
    const wNorm = w.trim();
    if (/^[\d+/*\-#.]+$/.test(wNorm)) {
      translatedTokens.push(wNorm);
    } else if (REVERSE_DICTIONARY[wNorm]) {
      translatedTokens.push(capitalizeWords(REVERSE_DICTIONARY[wNorm]));
    } else if (AR_NAMES[wNorm]) {
      translatedTokens.push(AR_NAMES[wNorm]);
    } else {
      // Keep as-is or capitalize
      translatedTokens.push(w);
    }
  }

  let finalEnglish = translatedTokens.join(' ').trim();
  if (extractedUnitEn) {
    finalEnglish = `${finalEnglish} ${extractedUnitEn}`;
  }

  return finalEnglish || trimmed;
}

/**
 * Universal auto-translator function (detects source language or accepts explicit direction)
 * @param {string} text - Text to translate
 * @param {string} [fromLang] - 'en', 'ar', 'English', 'Arabic' or auto
 * @param {string} [toLang] - 'en', 'ar', 'English', 'Arabic' or auto
 * @returns {string}
 */
export function autoTranslateText(text, fromLang, toLang) {
  if (!text || typeof text !== 'string') return '';
  const trimmed = text.trim();
  if (!trimmed) return '';

  const isAr = isArabicText(trimmed);
  const target = String(toLang || '').toLowerCase();
  
  if (target === 'ar' || target === 'arabic' || (!toLang && !isAr)) {
    return translateEnglishToArabic(trimmed);
  } else if (target === 'en' || target === 'english' || (!toLang && isAr)) {
    return translateArabicToEnglish(trimmed);
  }

  // If already matches target, return
  return isAr ? translateArabicToEnglish(trimmed) : translateEnglishToArabic(trimmed);
}

// Helpers
function cleanTranslation(val) {
  if (!val) return '';
  // If dictionary has slash variants e.g. "حبة / قطعة", pick first clean variant
  if (val.includes(' / ')) {
    return val.split(' / ')[0].trim();
  }
  return val.trim();
}

function capitalizeWords(str) {
  if (!str) return '';
  return str.replace(/\b\w/g, char => char.toUpperCase());
}

export default {
  translateEnglishToArabic,
  translateArabicToEnglish,
  autoTranslateText,
  isArabicText,
  DICTIONARY,
  REVERSE_DICTIONARY
};
