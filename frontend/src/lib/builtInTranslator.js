export function transliterateEnToAr(word) {
  if (!word) return '';
  const lower = word.toLowerCase().trim();
  if (DICTIONARY[lower]) return DICTIONARY[lower];
  if (EN_NAMES[lower]) return EN_NAMES[lower];
  
  let res = lower;
  for (const [pattern, rep] of PHONETIC_EN_TO_AR) {
    res = res.replace(pattern, rep);
  }
  // Clean double Arabic vowels
  res = res.replace(/اا+/g, 'ا').replace(/يي+/g, 'ي').replace(/وو+/g, 'و');
  return res;
}

// Check if string contains Arabic characters
